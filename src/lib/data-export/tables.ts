type OrgTable = SQLiteTable & { id: AnySQLiteColumn; orgId: AnySQLiteColumn };

/** One CSV in the export. `columns` is an explicit whitelist: header -> column. Anything not listed never leaves the DB. */
export type ExportTable = {
  file: string;
  table: OrgTable;
  columns: Record<string, AnySQLiteColumn>;
};

const define = <T extends OrgTable>(file: string, table: T, columns: Record<string, AnySQLiteColumn>): ExportTable => ({
  file,
  table,
  columns: { id: table.id, ...columns },
});

